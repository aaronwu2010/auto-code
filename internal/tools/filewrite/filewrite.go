func isUNCPath(path string) bool {
	return strings.HasPrefix(path, "\\\\") || strings.HasPrefix(path, "//")
}

func expandPath(path string) string {
	if strings.HasPrefix(path, "~") {
		home, err := os.UserHomeDir()
		if err == nil {
			return filepath.Join(home, path[1:])
		}
	}
	abs, err := filepath.Abs(path)
	if err != nil {
		return path
	}
	return abs
}

func ParseFileWriteInput(raw map[string]any) (FileWriteInput, error) {
	inp := FileWriteInput{}
	if v, ok := raw["file_path"].(string); ok {
		inp.FilePath = v
	}
	if v, ok := raw["content"].(string); ok {
		inp.Content = v
	}
	if v, ok := raw["auto_generated"].(bool); ok {
		inp.AutoGenerated = v
	}
	if inp.FilePath == "" {
		return inp, fmt.Errorf("file_path is required")
	}
	return inp, nil
}

// appendTimestamp 在文件名扩展名前插入 unix 时间戳（int64 秒）后缀，
// 例如 report.xlsx -> report_1723136400.xlsx，gen.py -> gen_1723136400.py。
func appendTimestamp(path string) string {
	ext := filepath.Ext(path)
	base := strings.TrimSuffix(path, ext)
	return fmt.Sprintf("%s_%d%s", base, time.Now().Unix(), ext)
}
