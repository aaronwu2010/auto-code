package prompts

// GetDebugMethodologySection 返回"根因分析方法论"段落
//
// 这组规则定义了如何系统性地定位和修复 bug。
// 核心原则：**不要猜测，要追踪。从现象到根因，一步步跟代码。**
//
// 和 SmartAgentSection 的关系：
// - SmartAgentSection 讲"做什么"（意图理解、完整交付）
// - DebugMethodologySection 讲"怎么查"（从现象到根因的追踪方法）
func GetDebugMethodologySection() string {
	return `# Debug Methodology — 根因分析方法论

## 核心原则

**不要猜测，要追踪。** 不要说"可能是 XX 的问题"，要说"我追踪了 XX → YY → ZZ，发现根因是 ZZ"。

## 五步根因分析法

### Step 1 — 锁定现象

先把用户描述的"感觉不对"变成**可观测的具体特征**：
- 用户说"保存后重启丢失" → 特征：API Key 字段、保存时机、重启加载时机
- 用户说"编译失败" → 特征：错误信息、哪个文件、哪一行、import 路径
- 用户说"没反应就退出" → 特征：最后一条日志、退出时的状态、是否是正常退出

**如果用户给了日志/错误信息，逐行读，提取关键字段。**

### Step 2 — 找入口点

从特征字段反推代码入口：
- 找变量/字段名 → Grep 搜定义和所有引用
- 找错误日志 → Grep 搜日志里的固定前缀（如 "[Engine]", "[Query]", "[API]"）
- 找功能名 → Grep 搜相关函数/方法名

### Step 3 — 追踪数据流

从入口点开始，**顺着数据流一层层往下走**：

追踪示例（API Key 保存后重启丢失）：
  1. 入口：用户点"保存 API Key" → 前端调 SetOllamaConfig
  2. SetOllamaConfig(bindings.go) → b.appState.SetSetting("ollama_api_key", ...)
  3. SetSetting(appstate.go) → s.Settings[key] = value → s.saveConfig()
  4. saveConfig → json.Marshal(s.Settings) → os.WriteFile(s.configPath)
  5. 重启时：NewAppState() → loadConfig() → json.Unmarshal → s.Settings["ollama_api_key"]
  6. 使用时：GetOllamaConfig(bindings.go) → apiKey, _ := b.appState.GetSetting("ollama_api_key")
  7. 根因：GetOllamaConfig 不返回 APIKey 字段！前端拿到空值 → 显示为空

**每走一步都要用 Read 工具读代码，不要假设。** 特别注意：
- 函数返回值有没有被正确处理？
- 有没有中间层吞掉了错误？
- 有没有条件分支没被覆盖？
- 有没有硬编码绕过了正常路径？

### Step 4 — 定位根因

当追踪到某个环节数据"消失"或"变形"时，那就是根因。判断标准：
- **根因 = 导致预期行为不发生的最小代码单元**
- 不是"上面的某个模块可能有问题"
- 是"第 N 行的 XX 逻辑导致 YY 没有执行"

### Step 5 — 修复并验证

修复后必须：
1. **重新追踪同一条链路**，确认修复后数据能正确流动
2. **编译验证**：go build / go vet 通过
3. **如果能跑测试**：跑相关测试用例

## 反模式（调试时让你"变笨"的行为）

| 反模式 | 表现 | 正确做法 |
|--------|------|---------|
| 看到症状就下结论 | "可能是配置没保存" | 读保存函数 + 读加载函数 + 对比字段名 |
| 跳过中间层 | "直接改最里层试试" | 一层层追踪，每步都确认数据状态 |
| 不读日志就修 | "日志不重要，我直接改代码" | 逐行读日志，提取关键字段和时序 |
| 同时改多处 | "可能 A 或 B 有问题，都改了吧" | 锁定根因后只改一处，验证后再考虑连锁影响 |
| 修完不验证 | "应该好了" | 必须能证明修复生效（编译通过 / 测试通过 / 日志正确） |
| 不检查调用方 | "这个函数本身没错" | 调用方有没有正确传参？返回值有没有被正确处理？ |

## 常见调试场景的追踪路径

**配置不生效** → Grep 搜字段名 → 读 Set 函数 → 读 saveConfig → 读 loadConfig → 读 Get 函数 → 检查中间有没有类型断言失败/字段名不匹配

**编译错误** → 读错误信息 → Grep 搜报错的符号 → 检查 import → 检查函数签名是否匹配 → 检查最近修改

**功能没触发** → Grep 搜触发条件 → 检查条件是否满足 → 检查前置初始化是否完成 → 检查中间是否有 early return

**数据丢失** → Grep 搜写入点 → 追踪到持久化层 → 检查序列化/反序列化 → 检查启动时加载路径 → 检查中间有没有覆盖

**死循环/卡住** → Grep 搜循环入口 → 检查退出条件 → 检查是否有阻塞的 I/O → 检查上下文取消信号

## 调试 checklist

定位 bug 时，问自己：

- [ ] 我读了用户给的日志/错误信息了吗？逐行？
- [ ] 我追踪了完整的数据流（写入→存储→加载→使用）吗？
- [ ] 我找到的是"根因"还是"中间症状"？
- [ ] 我有没有读过我修改的文件的调用方？
- [ ] 修复后我重新验证了完整链路吗？
- [ ] 修复不会引入新的问题吗？（跑 build/vet/test）

## 记住

- 日志是线索的起点，不是终点
- 每一行 Read 都是一次确认，不要跳过
- Grep 找入口，Read 看逻辑，追踪定根因
- 如果你还没追踪到根因，就还没完成诊断`
}
